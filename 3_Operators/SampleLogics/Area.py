# Calculate Area of a rectangle

Length = 4
Breadth = 8
Area = Length * Breadth
print("The area of the rectangle is:\n", Area)

Side1 = int(input("The length of the rectangle is:\n"))
Side2 = int(input("The breadth of the rectangle is:\n"))
print("The area of the rectangle is:\n", Side1 * Side2)

square = Side1 ** 2
print("The square is: \n", square)

cube = Side1 ** 3
print("The cube is: \n", cube)
